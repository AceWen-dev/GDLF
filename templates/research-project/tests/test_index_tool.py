from __future__ import annotations

import io
import json
import sys
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path

from dlef.candidates import Candidate, CandidateStore
from dlef.claim import Claim, ClaimStore
from dlef.run import RunStore

from core.tools import index as index_tool


class IndexToolTests(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        root = Path(self._tmp.name)
        self.runs_root = root / "runs"
        self.candidates_root = root / "candidates"
        self.claims_root = root / "claims"
        self.out = root / "INDEX.md"
        store = RunStore(self.runs_root)
        self.runs = []
        for experiment, seed, metric in (
            ("ranksim", 1, 2.5),
            ("ranksim", 2, 2.3),
            ("baseline", 1, 3.1),
        ):
            run = store.create(
                project="demo",
                experiment=experiment,
                config_digest=f"{seed:064d}",
                seed=seed,
            )
            run.log_metrics({"phase": "val", "epoch": 1, "mae": metric})
            run.finalize("completed")
            self.runs.append(run)

        CandidateStore(self.candidates_root).add(
            Candidate(
                candidate_id="ranksim-seeds",
                title="RankSim, 2 seeds",
                run_ids=(self.runs[0].run_id, self.runs[1].run_id),
                reason="best val mae",
                metric="mae",
                approved_by="twj 2026-11-18: ok",
            )
        )
        ClaimStore(self.claims_root).add(
            Claim(
                claim_id="main",
                text="Main result",
                eval_ids=("eval-1",),
                metric="mae",
                value=2.4,
                approved_by="twj 2026-11-18: ok",
            )
        )
        # A legacy claim written before approval tracking: no approved_by.
        legacy = {
            "claim_id": "legacy",
            "text": "Old claim",
            "eval_ids": ["eval-0"],
            "metric": "mae",
            "created_at": "2026-10-01T00:00:00+00:00",
        }
        (self.claims_root / "legacy.json").write_text(
            json.dumps(legacy), encoding="utf-8"
        )

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def _run_index(self) -> str:
        output = io.StringIO()
        previous = sys.argv
        sys.argv = [
            "index.py",
            "--runs",
            str(self.runs_root),
            "--candidates",
            str(self.candidates_root),
            "--claims",
            str(self.claims_root),
            "--out",
            str(self.out),
        ]
        try:
            with redirect_stdout(output):
                code = index_tool.main()
        finally:
            sys.argv = previous
        self.assertEqual(code, 0)
        return self.out.read_text(encoding="utf-8")

    def test_index_renders_all_sections(self) -> None:
        text = self._run_index()

        self.assertIn("generated by `make index`", text)
        self.assertIn("## Funnel", text)
        self.assertIn("## Experiments", text)
        self.assertIn("## Recent runs", text)
        self.assertIn("## Shortlist", text)
        self.assertIn("## Claims", text)
        self.assertIn("## Where to look", text)

        self.assertIn("| 3 | 0 | 3 | 0 |", text)  # runs/running/completed/failed
        self.assertIn("last val mae", text)      # experiments table reads val records
        self.assertIn("2.3", text)               # best val across ranksim seeds
        self.assertIn("ranksim", text)
        self.assertIn("baseline", text)
        self.assertIn("ranksim-seeds", text)
        self.assertIn("twj 2026-11-18: ok", text)
        self.assertIn("scratch", text)

    def test_unapproved_records_are_flagged(self) -> None:
        text = self._run_index()
        self.assertIn("WARN: 1 candidate/claim record(s)", text)
        self.assertIn("UNAPPROVED", text)
        self.assertIn("legacy", text)


if __name__ == "__main__":
    unittest.main()
