"""Embed the project template into the ``dlef`` package.

The source of truth is ``templates/research-project/``. This script creates
``dlef/_template_data.py`` so a wheel installed on another machine can run
``dlef init`` without a DLEF checkout.

Run after changing the template:

    python tools/build_template_data.py
    make template-data
"""

from __future__ import annotations

import base64
import io
import textwrap
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "templates" / "research-project"
OUTPUT = ROOT / "dlef" / "_template_data.py"
EXCLUDED_DIRS = {"__pycache__"}
EXCLUDED_OUTPUT = {"runs", "artifacts", "sweeps", "test_access"}


def _files(root: Path) -> list[tuple[Path, Path]]:
    files: list[tuple[Path, Path]] = []
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(root)
        if any(part in EXCLUDED_DIRS for part in rel.parts):
            continue
        if path.suffix == ".pyc":
            continue
        if rel.parts and rel.parts[0] == "output" and len(rel.parts) > 1:
            if rel.parts[1] in EXCLUDED_OUTPUT:
                continue
        files.append((path, rel))
    return files


def build_archive(root: Path = TEMPLATE) -> bytes:
    """Build a deterministic zip of the template contents."""

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for path, rel in _files(root):
            name = (Path("research-project") / rel).as_posix()
            info = zipfile.ZipInfo(name)
            info.date_time = (1980, 1, 1, 0, 0, 0)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, path.read_bytes())
    return buffer.getvalue()


def main() -> int:
    if not TEMPLATE.is_dir():
        raise SystemExit(f"template not found: {TEMPLATE}")
    archive = build_archive()
    encoded = base64.b64encode(archive).decode("ascii")
    wrapped = "\n".join(textwrap.wrap(encoded, 100))
    OUTPUT.write_text(
        '"""Generated by tools/build_template_data.py; do not edit."""\n\n'
        'TEMPLATE_B64 = """\\\n'
        f"{wrapped}\n"
        '"""\n',
        encoding="utf-8",
    )
    print(f"wrote {OUTPUT} ({len(archive)} bytes archive, {len(encoded)} base64 chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
